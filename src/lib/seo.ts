import type { Metadata } from "next";
import { site } from "@/config/site";

type PageSeo = {
  /** Page title. The brand is appended unless `absolute` is set. */
  title: string;
  absolute?: boolean;
  description: string;
  /** Path from the site root, used for the canonical URL. */
  path: string;
  type?: "website" | "article";
  publishedTime?: string;
  modifiedTime?: string;
  /** Share image path. Pages with their own opengraph-image file pass it here. */
  image?: string;
};

/**
 * Builds the full metadata for a page in one place. Next.js replaces rather
 * than merges a page's `openGraph` object, so each page gets every field here
 * to keep site name, locale and URL on every share preview.
 * Share images are generated by the `opengraph-image` files.
 */
export function pageMetadata({
  title,
  absolute = false,
  description,
  path,
  type = "website",
  publishedTime,
  modifiedTime,
  image = "/opengraph-image",
}: PageSeo): Metadata {
  const fullTitle = absolute ? title : `${title} | ${site.shortName}`;
  return {
    title: { absolute: fullTitle },
    description,
    alternates: { canonical: path },
    openGraph: {
      type,
      url: path,
      title: fullTitle,
      description,
      siteName: site.name,
      locale: "en_AE",
      images: [{ url: image, width: 1200, height: 630, alt: fullTitle }],
      ...(publishedTime
        ? { publishedTime, modifiedTime: modifiedTime ?? publishedTime }
        : {}),
    },
    // No twitter image on purpose: X falls back to the page's og:image.
    twitter: { card: "summary_large_image", title: fullTitle, description },
  };
}
